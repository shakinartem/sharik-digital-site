/**
 * Ответ после сохранения контакта.
 *
 * Раньше текст был один на оба направления и продавцу уходило
 * «где клиника может терять пациентов». Теперь формулировка
 * зависит от направления.
 */
export function buildContactSavedText(track: TrackKey = "clinic") {
  // Формулировки повторяют nouns из main menu: обещание и ответ
  // должны звучать одинаково, иначе человек не понимает, о чём
  // вообще речь — раньше здесь обещали «разбор клиники» продавцу.
  return track === KIT
    ? [
        "Готово, контакт сохранил и передал команде.",
        "",
        "Посмотрим ваши ответы и напишем, чтобы разобрать канал продаж:",
        "что переносим, что придётся делать заново и есть ли смысл запускать свой магазин.",
        "",
        "Обычно отвечаем в рабочее время, в течение дня.",
      ].join("\n")
    : [
        "Готово, контакт сохранил и передал команде.",
        "",
        "Посмотрим ваши ответы и напишем, чтобы разобрать клинику:",
        "где теряются пациенты и что закрывать в первую очередь.",
        "",
        "Обычно отвечаем в рабочее время, в течение дня.",
      ].join("\n");
}

