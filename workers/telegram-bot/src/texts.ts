import { KIT, type TrackKey } from "./tracks";

/**
 * Тексты бота.
 *
 * Правила, которые здесь соблюдаются:
 * - каждое сообщение знает направление. Продавцу нельзя писать
 *   «где клиника теряет пациентов»: раньше бот отдавал ему именно
 *   этот текст, и человек уходил, не понимая, куда попал;
 * - кавычки только «ёлочки». Английские “кавычки” и прямые кавычки
 *   в русском тексте выглядят как опечатка;
 * - никаких выдуманных кейсов: у направления продавцов он один,
 *   и текст говорит об этом прямо;
 * - сообщение отвечает на вопрос «что будет дальше» — иначе
 *   человек не понимает, зачем отвечать.
 */

/**
 * Направление человеческим языком — для подстановок в тексты.
 *
 * Словарь намеренно маленький: только те формы, что реально
 * подставляются. Лишние поля в объекте выглядят как конфиг, но
 * ничем не управляют — их стоило удалить вместе с правками.
 */
function noun(track: TrackKey) {
  return track === KIT
    ? {
        who: "продавцам маркетплейсов",
        gain: "сколько заказов может дать собственный канал",
        result: "разбор вашего канала продаж",
      }
    : {
        who: "стоматологиям",
        gain: "сколько пациентов можно вернуть",
        result: "разбор вашей клиники",
      };
}

export function buildMainMenuText(track: TrackKey = "clinic") {
  const n = noun(track);

  return [
    "Привет! Это бот ШАРиК digital.",
    "",
    `Помогаем ${n.who} — считаем ${n.gain}, и если это имеет смысл,`,
    "собираем рабочую систему вокруг вашего бизнеса.",
    "",
    "Что можно сделать прямо сейчас:",
    "",
    "• Пройти мини-диагностику и увидеть, где теряются деньги.",
    "• Забрать чек-лист — с него проще всего начать.",
    "• Посмотреть кейсы.",
    "• Задать вопрос и получить ответ от команды.",
    "",
    "Начните с чек-листа или диагностики — оба варианта бесплатные.",
  ].join("\n");
}

